/**
 * Rose Griffon ops: one uniform verb set over the host roles (infra/hosts.toml) and the
 * service registry (infra/services.toml). The justfile and `rg <verb>` are thin wrappers.
 *
 *   host <role|host> [field]           print a resolved host (or one field)
 *   ssh <role|host> [-- cmd...]        ssh to the host holding a role
 *   env <role|host>                    compose env exported on that host (KEY=VALUE)
 *   services [--json]                  the registry
 *   render [--check]                   regenerate nginx config from the registry
 *   build <service|all> [--role build] [--ref origin/main]
 *   deploy <service|all> [--role <svc role>] [--ref origin/main] [--build-here]
 *   verify <service|all> [--role <svc role>]
 *   rollback <tag> [service|all] [--role <svc role>]
 *   migrate <service> --to <role|host> [--from <role|host>] [--ref origin/main] [--apply]
 *
 * Remote verbs pipe a generated script to `ssh <alias> bash -s`; `--dry-run` prints it.
 * migrate is a dry run unless --apply. Nothing here touches DNS.
 */

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import {
  REPO_ROOT,
  composeEnv,
  type Host,
  hostByKey,
  loadInfra,
  renderComposeEnv,
  renderTemplate,
  renderUpstreams,
  resolveHost,
  service,
  services,
} from "../../packages/rg-config/infra.ts";
import {
  buildScript,
  deployScript,
  migratePlan,
  rollbackScript,
  select,
  verifyScript,
} from "./scripts.ts";

const env = process.env;
const infra = loadInfra();

/** nginx files generated by `render`: output -> template (null = upstreams from the registry). */
export const RENDERED: Record<string, string | null> = {
  "infra/docker/nginx/conf.d/00-upstreams.conf": null,
  "infra/docker/nginx/conf.d/rosegriffon.fr.conf":
    "infra/docker/nginx/templates/rosegriffon.fr.conf",
  "infra/docker/nginx/conf.d/rg-core.conf":
    "infra/docker/nginx/templates/rg-core.conf",
  "infra/docker/host-nginx/rosegriffon-stack.conf":
    "infra/docker/host-nginx/templates/rosegriffon-stack.conf",
};

/** Every generated file: nginx from templates, plus one compose env file per host. */
export function renderedFiles(): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [file, tmpl] of Object.entries(RENDERED))
    out[file] =
      tmpl === null
        ? renderUpstreams(infra)
        : `# GENERATED by \`just render\` from ${tmpl}. Do not edit.\n${renderTemplate(readFileSync(resolve(REPO_ROOT, tmpl), "utf8"), infra, env)}`;
  for (const key of Object.keys(infra.hosts.hosts))
    out[`infra/generated/compose.${key}.env`] = renderComposeEnv(
      hostByKey(infra, key, env),
      infra,
      env,
    );
  return out;
}

interface Args {
  pos: string[];
  flags: Record<string, string | true>;
  rest: string[];
}

function parse(argv: string[]): Args {
  const dash = argv.indexOf("--");
  const head = dash < 0 ? argv : argv.slice(0, dash);
  const rest = dash < 0 ? [] : argv.slice(dash + 1);
  const pos: string[] = [];
  const flags: Args["flags"] = {};
  for (let i = 0; i < head.length; i++) {
    const a = head[i]!;
    if (!a.startsWith("--")) {
      pos.push(a);
      continue;
    }
    const [k, inline] = a.slice(2).split("=", 2) as [
      string,
      string | undefined,
    ];
    const next = head[i + 1];
    if (inline !== undefined) flags[k] = inline;
    else if (
      next !== undefined &&
      !next.startsWith("--") &&
      !["apply", "check", "json", "dry-run"].includes(k)
    ) {
      flags[k] = next;
      i++;
    } else flags[k] = true;
  }
  return { pos, flags, rest };
}

const str = (v: string | true | undefined, d: string) =>
  typeof v === "string" && v ? v : d;

async function remote(
  host: Host,
  script: string,
  dry: boolean,
): Promise<number> {
  if (dry) {
    console.log(`# --- ${host.key} (ssh ${host.ssh}) ---\n${script}\n`);
    return 0;
  }
  const proc = Bun.spawn(
    ["ssh", "-o", "BatchMode=yes", host.ssh, "bash", "-s"],
    {
      stdin: new TextEncoder().encode(`${script}\n`),
      stdout: "inherit",
      stderr: "inherit",
    },
  );
  return proc.exited;
}

function roleFor(name: string, flags: Args["flags"]): string {
  if (typeof flags.role === "string") return flags.role;
  if (name === "all" || name === "") return "prod";
  return service(infra, name).role;
}

function render(check: boolean): number {
  let stale = 0;
  for (const [out, want] of Object.entries(renderedFiles())) {
    const path = resolve(REPO_ROOT, out);
    let have = "";
    try {
      have = readFileSync(path, "utf8");
    } catch {}
    if (have === want) continue;
    if (check) {
      console.error(`stale: ${out} (run: just render)`);
      stale++;
    } else {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, want);
      console.log(`wrote ${out}`);
    }
  }
  return stale ? 1 : 0;
}

async function main(argv: string[]): Promise<number> {
  const [verb = "help", ...tail] = argv;
  const { pos, flags, rest } = parse(tail);
  const dry = flags["dry-run"] === true;
  const ref = str(flags.ref, "origin/main");

  switch (verb) {
    case "host": {
      const h = resolveHost(infra, pos[0] ?? "prod", env);
      const field = pos[1] as keyof Host | undefined;
      console.log(field ? String(h[field] ?? "") : JSON.stringify(h, null, 2));
      return 0;
    }
    case "ssh": {
      const h = resolveHost(infra, pos[0] ?? "prod", env);
      const proc = Bun.spawn(["ssh", h.ssh, ...rest], {
        stdin: "inherit",
        stdout: "inherit",
        stderr: "inherit",
      });
      return proc.exited;
    }
    case "env": {
      const h = resolveHost(infra, pos[0] ?? "prod", env);
      for (const [k, v] of Object.entries(composeEnv(h, infra, env)))
        console.log(`${k}=${v}`);
      return 0;
    }
    case "services": {
      const list = services(infra);
      if (flags.json) console.log(JSON.stringify(list, null, 2));
      else
        for (const s of list)
          console.log(
            `${s.name.padEnd(12)} role=${s.role.padEnd(8)} host=${resolveHost(infra, s.role, env).key.padEnd(5)} ${s.target ? `target=${s.target}` : `image=${s.image ?? s.dockerfile}`}${s.port ? ` :${s.port}${s.health ?? ""}` : ""}${s.profile ? ` profile=${s.profile}` : ""}`,
          );
      return 0;
    }
    case "render":
      return render(flags.check === true);
    case "build": {
      const name = pos[0] ?? "all";
      const host = resolveHost(infra, str(flags.role, "build"), env);
      return remote(
        host,
        buildScript(host, infra, env, select(infra, name), ref),
        dry,
      );
    }
    case "deploy": {
      const name = pos[0] ?? "all";
      const host = resolveHost(infra, roleFor(name, flags), env);
      const code = await remote(
        host,
        deployScript(
          host,
          infra,
          env,
          select(infra, name),
          ref,
          name === "all",
          // Images come from the build role (`just build`) unless --build-here.
          flags["build-here"] ? undefined : resolveHost(infra, "build", env),
        ),
        dry,
      );
      if (code !== 0 || dry) return code;
      return remote(
        host,
        verifyScript(host, infra, env, select(infra, name)),
        false,
      );
    }
    case "verify": {
      const name = pos[0] ?? "all";
      const host = resolveHost(infra, roleFor(name, flags), env);
      return remote(
        host,
        verifyScript(host, infra, env, select(infra, name)),
        dry,
      );
    }
    case "rollback": {
      const tag = pos[0];
      if (!tag)
        throw new Error(
          "rollback <tag> [service]: tag is the RG_TAG of the last good deploy",
        );
      const name = pos[1] ?? "all";
      const host = resolveHost(infra, roleFor(name, flags), env);
      return remote(
        host,
        rollbackScript(
          host,
          infra,
          env,
          select(infra, name),
          tag,
          name === "all",
        ),
        dry,
      );
    }
    case "migrate": {
      const name = pos[0];
      if (!name || typeof flags.to !== "string")
        throw new Error(
          "migrate <service> --to <role|host> [--from <role|host>] [--apply]",
        );
      const svc = service(infra, name);
      const from = resolveHost(infra, str(flags.from, svc.role), env);
      const to = resolveHost(infra, flags.to, env);
      const plan = migratePlan(infra, env, svc, from, to, ref);
      const apply = flags.apply === true;
      console.log(
        `migrate ${svc.name}: ${from.key} -> ${to.key}${apply ? "" : " (dry run, add --apply)"}`,
      );
      for (const [i, step] of plan.entries()) {
        console.log(`\n[${i + 1}/${plan.length}] ${step.title}`);
        const code = await remote(step.host, step.script, !apply);
        if (code !== 0) {
          console.error(
            `step ${i + 1} failed (${code}); ${i >= 1 ? `restart on ${from.key}: just deploy ${svc.name} --role ${from.key}` : "nothing changed"}`,
          );
          return code;
        }
      }
      console.log(
        `\nnext: point role "${svc.role}" at ${to.key} in infra/hosts.toml (or RG_HOST_${svc.role.toUpperCase()}=${to.key}), ` +
          `then repoint the public proxy/DNS for ${svc.vhosts.join(", ") || svc.name}. State on ${from.key} is kept for rollback.`,
      );
      return 0;
    }
    default:
      console.log(
        readFileSync(import.meta.path, "utf8")
          .split("*/")[0]!
          .replace(/^#!.*\n\/\/.*\n\/\*\*\n/, "")
          .replace(/^ \* ?/gm, ""),
      );
      return verb === "help" || verb === "--help" ? 0 : 1;
  }
}

if (import.meta.main) {
  try {
    process.exit(await main(process.argv.slice(2)));
  } catch (e) {
    console.error(`ops: ${(e as Error).message}`);
    process.exit(2);
  }
}
