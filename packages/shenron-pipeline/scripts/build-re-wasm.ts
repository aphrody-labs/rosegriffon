/**
 * Compiles `crates/shenron-re` to WebAssembly (`wasm32-unknown-unknown`)
 * and generates web bindings via `wasm-bindgen`.
 *
 *   bun packages/pipeline/scripts/build-re-wasm.ts
 */

import { existsSync } from "node:fs";
import { createHash } from "node:crypto";
import { mkdir, copyFile, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";

const ROOT = join(import.meta.dir, "..", "..", "..");
const CRATE = "shenron-re";
const TARGET = "wasm32-unknown-unknown";
const OUT_DIR = join(ROOT, "packages", "pipeline", "src", "wasm");
const PKG_DIR = join(ROOT, "crates", "shenron-re", "pkg");
const SITE_WASM_DIR = join(ROOT, "apps", "site", "public", "wasm");

console.log(`▶ Building ${CRATE} for ${TARGET} in release mode...`);
const cargo = Bun.spawnSync(
  ["cargo", "build", "-p", CRATE, "--target", TARGET, "--release", "--locked"],
  {
    cwd: ROOT,
    stdout: "inherit",
    stderr: "inherit",
  },
);

if (cargo.exitCode !== 0) {
  console.error("✗ Cargo build failed");
  process.exit(1);
}

const wasmPath = join(ROOT, "target", TARGET, "release", "shenron_re.wasm");
if (!existsSync(wasmPath)) {
  console.error(`✗ Output binary not found at ${wasmPath}`);
  process.exit(1);
}

console.log(`▶ Running wasm-bindgen on ${wasmPath}...`);
const bindgen = Bun.spawnSync(["wasm-bindgen", wasmPath, "--out-dir", PKG_DIR, "--target", "web"], {
  cwd: ROOT,
  stdout: "inherit",
  stderr: "inherit",
});

if (bindgen.exitCode !== 0) {
  console.error("✗ wasm-bindgen failed");
  process.exit(1);
}

await mkdir(OUT_DIR, { recursive: true });
for (const file of [
  "shenron_re.d.ts",
  "shenron_re.js",
  "shenron_re_bg.wasm",
  "shenron_re_bg.wasm.d.ts",
]) {
  await copyFile(join(PKG_DIR, file), join(OUT_DIR, file));
}

const lock = await Bun.file(join(ROOT, "Cargo.lock")).text();
const expectedBindgen = /\[\[package\]\]\r?\nname = "wasm-bindgen"\r?\nversion = "([^"]+)"/.exec(
  lock,
)?.[1];
const bindgenVersion = Bun.spawnSync(["wasm-bindgen", "--version"], {
  cwd: ROOT,
  stdout: "pipe",
  stderr: "pipe",
});
if (
  !expectedBindgen ||
  bindgenVersion.exitCode !== 0 ||
  !bindgenVersion.stdout.toString().includes(expectedBindgen)
) {
  console.error(
    `✗ wasm-bindgen CLI must match Cargo.lock (${expectedBindgen ?? "version not found"}); ` +
      bindgenVersion.stderr.toString().trim(),
  );
  process.exit(1);
}

// `wasm-bindgen --target web` now emits a self-contained JS glue file; older
// releases emitted a separate `_bg.js` shim which is no longer generated.
await rm(join(OUT_DIR, "shenron_re_bg.js"), { force: true });

const wasmBytes = await Bun.file(join(PKG_DIR, "shenron_re_bg.wasm")).bytes();
const sha256 = createHash("sha256").update(wasmBytes).digest("hex");
const filename = `shenron_re_bg.${sha256.slice(0, 16)}.wasm`;
await mkdir(SITE_WASM_DIR, { recursive: true });
await copyFile(join(PKG_DIR, "shenron_re_bg.wasm"), join(SITE_WASM_DIR, filename));
await writeFile(
  join(OUT_DIR, "re-wasm-asset.ts"),
  `// SPDX-License-Identifier: Apache-2.0\n// Generated by packages/pipeline/scripts/build-re-wasm.ts.\n` +
    `export const SHENRON_RE_WASM_FILENAME = ${JSON.stringify(filename)};\n` +
    `export const SHENRON_RE_WASM_SHA256 = ${JSON.stringify(sha256)};\n`,
);

console.log(`✓ shenron-re WASM pipeline staged to ${OUT_DIR} and ${SITE_WASM_DIR}/${filename}`);
