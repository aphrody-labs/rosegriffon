/**
 * Rose Griffon authentication (Better Auth), end to end, offline.
 *
 * FLOW UNDER TEST (apps/rg-website -> createRoseGriffonAuth)
 * - Origin https://rosegriffon.fr, basePath /api/auth (route `app/api/auth/[...all]`).
 * - Email/password: POST /sign-up/email (no session: email verification is
 *   required), GET /verify-email?token=..., POST /sign-in/email -> session
 *   cookie `better-auth.session_token` (`__Secure-` prefix + Secure in
 *   production, HttpOnly, SameSite=Lax, host-only), GET /get-session,
 *   POST /sign-out.
 * - Social OAuth: POST /sign-in/social {provider} -> provider authorize URL with
 *   client_id, redirect_uri = https://rosegriffon.fr/api/auth/callback/<id>,
 *   state (stored in the `verification` table, storeStateStrategy "database",
 *   bound to a signed `state` cookie); GET /callback/<id>?code&state exchanges
 *   the code at the provider token endpoint and reads its userinfo endpoint.
 *   Patreon is a genericOAuth provider, which Better Auth 1.7 registers as a
 *   social provider: same /sign-in/social and /callback/patreon endpoints.
 * - Account linking: enabled, trusted providers = configured social providers
 *   + patreon, so a verified provider email attaches to the existing user.
 * - Secret: BETTER_AUTH_SECRET. Store: public."user" / session / account.
 *
 * Every secret here is generated by the test; the database is Better Auth's
 * memory adapter; provider endpoints are answered by an intercepted `fetch`.
 */
