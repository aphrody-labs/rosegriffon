#!/usr/bin/env bun
// Builds a NON-destructive restore script for the inagle columns that the game push
// emptied in prod (rg-inagle-pg) but that the Supabase `rg` snapshot still has.
// Reads both databases read-only; writes var/wiki-restauration-colonnes.sql.
// Every UPDATE only fills values that are NULL in prod (coalesce), keyed by id.
//
// Usage: SUPA_URL=... INAGLE_DATABASE_URL=... bun tools/crawl/wiki-restore-sql.ts

import { SQL } from "bun";

const ROOT = new URL("../../", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const supa = new SQL(process.env.SUPA_URL!, { max: 1 });
const prod = new SQL(process.env.INAGLE_DATABASE_URL!, { max: 1 });
await supa`set default_transaction_read_only = on`;
await prod`set default_transaction_read_only = on`;

/** Columns to restore per table, with the SQL type used in the VALUES list. */
const PLAN: Record<string, Record<string, string>> = {
  inagle_characters: {
    age_group: "text",
    constellation: "text",
    constellation_index: "integer",
    control_type: "text",
    hero_type: "text",
    nickname: "text",
    school_year: "text",
    stat_lv1_agilite: "integer",
    stat_lv1_controle: "integer",
    stat_lv1_frappe: "integer",
    stat_lv1_intelligence: "integer",
    stat_lv1_physique: "integer",
    stat_lv1_pression: "integer",
    stat_lv1_technique: "integer",
    team_id: "text",
    zukan_hash: "text",
  },
  inagle_formations: { name_en: "text", name_fr: "text", name_ja: "text" },
  inagle_items: { stat_boost_1: "text", stat_boost_2: "text" },
  inagle_passives: {
    description_en: "text",
    description_fr: "text",
    description_ja: "text",
    name_en: "text",
    name_fr: "text",
    name_ja: "text",
  },
  inagle_skills: { evolution_type: "text", growth_type: "text" },
};

const lit = (v: unknown): string => {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  const s = typeof v === "object" ? JSON.stringify(v) : String(v);
  return `'${s.replaceAll("'", "''")}'`;
};

const out: string[] = [
  "-- Restore of inagle columns emptied in prod by the game push (generated by tools/crawl/wiki-restore-sql.ts).",
  "-- Source: Supabase project `rg`, public.inagle_* (snapshot copied to rg-inagle-pg on 2026-10-17/22).",
  "-- Only fills NULL values in prod; never overwrites a value the push wrote. Review, then run inside rg-inagle-pg.",
  "begin;",
];
const stats: string[] = [];

for (const [table, cols] of Object.entries(PLAN)) {
  const names = Object.keys(cols);
  // Postgres may store numbers as text in some columns: read the real types from prod.
  const types = new Map(
    (
      await prod.unsafe(
        `select column_name, format_type(atttypid, atttypmod) t from information_schema.columns c
         join pg_attribute a on a.attrelid = '${table}'::regclass and a.attname = c.column_name
         where c.table_name = '${table}'`,
      )
    ).map((r: any) => [r.column_name, r.t]),
  );
  const prodIds = new Set((await prod.unsafe(`select id from ${table}`)).map((r: any) => String(r.id)));
  const src = (await supa.unsafe(
    `select id, ${names.join(", ")} from ${table} where ${names.map(n => `${n} is not null`).join(" or ")}`,
  )) as Record<string, unknown>[];
  const rows = src.filter(r => prodIds.has(String(r.id)));
  stats.push(`${table}: ${rows.length} rows (${src.length} in snapshot)`);
  if (!rows.length) continue;
  const castCols = names.map(n => `${n}::${types.get(n) ?? cols[n]}`);
  for (let i = 0; i < rows.length; i += 500) {
    const chunk = rows.slice(i, i + 500);
    out.push(
      `update ${table} t set ${names.map(n => `${n} = coalesce(t.${n}, v.${n})`).join(", ")}`,
      `from (select id::text, ${castCols.join(", ")} from (values`,
      chunk.map(r => `  (${[r.id, ...names.map(n => r[n])].map(lit).join(", ")})`).join(",\n"),
      `) as x(id, ${names.join(", ")})) v(id, ${names.join(", ")})`,
      `where t.id::text = v.id;`,
    );
  }
}

// Passive rows lost their resolved JSON (names, effect id, values): restore `data` only where prod has no name.
const passives = (await supa`select id, data from inagle_passives where jsonb_typeof(data->'name') = 'object'`) as { id: string; data: unknown }[];
stats.push(`inagle_passives.data: ${passives.length} rows`);
for (let i = 0; i < passives.length; i += 300) {
  out.push(
    "update inagle_passives t set data = v.data from (values",
    passives
      .slice(i, i + 300)
      .map(r => `  (${lit(r.id)}, ${lit(r.data)}::jsonb)`)
      .join(",\n"),
    ") v(id, data) where t.id = v.id and (t.data->'name' is null or jsonb_typeof(t.data->'name') = 'null');",
  );
}
out.push("commit;", "");
await Bun.write(`${ROOT}var/wiki-restauration-colonnes.sql`, out.join("\n"));
console.log(stats.join("\n"));
await supa.close();
await prod.close();
